import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
const dom = new JSDOM('', { url: 'http://localhost/' });
for (const key of ['window', 'document', 'localStorage', 'sessionStorage', 'CustomEvent', 'StorageEvent'] as const) Object.defineProperty(globalThis, key, { value: dom.window[key], configurable: true });
const { localSessionStore: store } = await import('../src/sessionStore.ts');
const game = store.create(100000, 2);
store.join(game.code, 'a', 'A'); store.join(game.code, 'b', 'B');
let session = store.startGame(game.code);
let pair = session.pairings.find(p => p.roundKey === '1a')!;
session.strategicTechnicalIssues.push({ pairingId: pair.id, playerId: pair.playerA, roundKey: '1a', role: 'proposer', detectedAt: new Date().toISOString() });
store.replaceFromRemote(session);
assert.throws(() => store.trainerSubmitStrategicDecision(game.code, pair.playerA as string, 100001));
session = store.trainerSubmitStrategicDecision(game.code, pair.playerA as string, 30000);
assert.equal(session.strategicTechnicalIssues[0].resolution, 'decision_received');
assert.equal(session.manualCorrections[0].afterValue, 30000);
assert.throws(() => store.trainerSubmitStrategicDecision(game.code, pair.playerA as string, 40000));
session = store.trainerSubmitStrategicDecision(game.code, pair.playerB as string, true);
assert.equal(store.roundProgress(session).complete, true);
session = store.closeStrategicRound(game.code);
assert.equal(session.closedRounds.includes('1a'), true);
session = store.nextRound(game.code);
pair = session.pairings.find(p => p.roundKey === '1b')!;
session.strategicTechnicalIssues.push({ pairingId: pair.id, playerId: pair.playerA, roundKey: '1b', role: 'proposer', detectedAt: new Date().toISOString() });
store.replaceFromRemote(session);
session = store.setPlayerBotControl(game.code, pair.playerA as string, true);
assert.ok(session.decisions.some(d => d.pairingId === pair.id && d.isBotDecision));
assert.ok(session.strategicTechnicalIssues.find(i => i.pairingId === pair.id)?.resolvedAt);
session.roundKey = '4'; session.publicGoodsPhase = 'setup'; session.groups = []; session.publicGoodsRoundNumber = 0; session.publicGoodsRounds = [];
store.replaceFromRemote(session);
store.randomizeGroups(game.code, 1); store.startPublicGoodsRound(game.code);
const id = pair.playerB as string;
session = store.trainerSubmitPublicGoods(game.code, id, 1000);
assert.equal(session.decisions.find(d => d.type === 'public_goods_contribution' && d.playerId === id)?.submissionSource, 'manual_correction');
assert.throws(() => store.submitPublicGoods(game.code, id, 2000));
console.log('TRAINER INTERVENTION TEST OK');
process.exit(0);
